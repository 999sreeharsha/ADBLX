public struct ParsedDNSQuery {
    public let ipVersion: IPVersion
    
    // IPv4 Address fields (network byte order / raw)
    public let srcIPv4: UInt32
    public let dstIPv4: UInt32
    
    // IPv6 Address fields (16 bytes each)
    public let srcIPv6: (UInt64, UInt64)
    public let dstIPv6: (UInt64, UInt64)
    
    // UDP Ports
    public let srcPort: UInt16
    public let dstPort: UInt16
    
    // Packet Offsets
    public let ipHeaderLength: Int
    public let udpHeaderOffset: Int
    public let dnsHeaderOffset: Int
    public let questionOffset: Int
    public let questionLength: Int
    
    // DNS Fields
    public let transactionID: UInt16
    public let flags: UInt16
    public let questionCount: UInt16
    public let qtype: UInt16
    public let qclass: UInt16
    
    // Reversed Domain bytes (e.g. "net.doubleclick.ad")
    public let reversedDomain: InlineReversedDomainBuffer
}
