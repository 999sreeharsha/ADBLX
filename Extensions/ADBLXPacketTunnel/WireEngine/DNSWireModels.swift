        guard count < 256 else { return false }
        withUnsafeMutableBytes(of: &storage) { ptr in
            ptr[count] = byte
        }
        count += 1
        return true
    }
    
    public mutating func append(bytes: UnsafeBufferPointer<UInt8>) -> Bool {
        guard count + bytes.count <= 256, let base = bytes.baseAddress else { return false }
        withUnsafeMutableBytes(of: &storage) { ptr in
            for i in 0..<bytes.count {
                ptr[count + i] = base[i]
            }
        }
        count += bytes.count
        return true
    }
    
    public func withUnsafeBufferPointer<R>(_ body: (UnsafeBufferPointer<UInt8>) throws -> R) rethrows -> R {
        return try withUnsafeBytes(of: storage) { raw in
            let base = raw.baseAddress!.assumingMemoryBound(to: UInt8.self)
