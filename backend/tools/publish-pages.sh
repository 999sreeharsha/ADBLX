#!/usr/bin/env bash
set -euo pipefail

# Deploys backend/public/ (produced by `swift run Publisher publish`) to the
# gh-pages branch of this repo via a persistent git worktree at
# .gh-pages-worktree/. Self-bootstraps the orphan gh-pages branch and the
# worktree on first run; idempotent on every run after.
#
# This script has no knowledge of filter groups, manifest structure, or
# versions — it copies backend/public/ verbatim. See docs/Architecture/Publisher.md.

REPO_ROOT="$(git rev-parse --show-toplevel)"
WORKTREE_DIR="$REPO_ROOT/.gh-pages-worktree"
PUBLIC_DIR="$REPO_ROOT/backend/public"

cd "$REPO_ROOT"

if [ ! -d "$PUBLIC_DIR" ]; then
  echo "error: $PUBLIC_DIR does not exist — run 'swift run Publisher publish --publish-base-url <url>' first" >&2
  exit 1
fi

if ! git show-ref --verify --quiet refs/remotes/origin/gh-pages; then
  echo "origin/gh-pages does not exist — bootstrapping orphan branch"
  BOOTSTRAP_DIR="$(mktemp -d)"
  git worktree add --detach "$BOOTSTRAP_DIR" >/dev/null
  (
    cd "$BOOTSTRAP_DIR"
    git checkout --orphan gh-pages
    git rm -rf . >/dev/null 2>&1 || true
    echo "# GitHub Pages output for ADBLX manifest/filters. Generated by backend/tools/publish-pages.sh — do not edit by hand." > README.md
    git add README.md
    git commit -m "chore: bootstrap gh-pages branch"
    git push origin gh-pages
  )
  git worktree remove --force "$BOOTSTRAP_DIR"
fi

if [ ! -d "$WORKTREE_DIR" ]; then
  echo "creating persistent worktree at $WORKTREE_DIR"
  git fetch origin gh-pages
  git worktree add "$WORKTREE_DIR" gh-pages
fi

cd "$WORKTREE_DIR"
git fetch origin gh-pages
git reset --hard origin/gh-pages

# Copy backend/public/ contents verbatim, preserving README.md (bootstrap marker).
find . -mindepth 1 -maxdepth 1 -not -name '.git' -not -name 'README.md' -exec rm -rf {} +
cp -R "$PUBLIC_DIR"/. "$WORKTREE_DIR"/

# Create standard entry index.html for GitHub Pages
cat << 'EOF' > index.html
<!doctype html>
<html>
<head>
  <meta charset="utf-8">
  <title>ADBLX Filter Registry</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; max-width: 600px; margin: 40px auto; padding: 0 20px; line-height: 1.6; color: #333; }
    h1 { color: #111; }
    a { color: #0066cc; text-decoration: none; }
    a:hover { text-decoration: underline; }
  </style>
</head>
<body>
  <h1>ADBLX Filter Registry</h1>
  <p>This site hosts ADBLX filter manifests and filter payloads for the SHIELD ad blocker application.</p>
  <ul>
    <li><a href="manifest.json">manifest.json</a></li>
  </ul>
</body>
</html>
EOF


git add -A

if git diff --cached --quiet; then
  echo "No changes to publish."
  exit 0
fi

git commit -m "chore: publish manifest and filters"
git push origin gh-pages
echo "Published to gh-pages."
